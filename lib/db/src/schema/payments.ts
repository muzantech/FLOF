import { pgTable, text, serial, integer, timestamp, jsonb } from "drizzle-orm/pg-core";
import { usersTable } from "./users";

export const paymentTransactionsTable = pgTable("payment_transactions", {
  id: serial("id").primaryKey(),
  userId: integer("user_id").notNull().references(() => usersTable.id, { onDelete: "cascade" }),
  paymentId: text("payment_id").notNull().unique(), // UUID generated by us
  tokenPay: text("token_pay"), // MoneyFusion token
  amount: integer("amount").notNull(), // in FCFA
  currency: text("currency").notNull().default("XOF"),
  type: text("type").notNull(), // coins | plan | marketplace
  status: text("status").notNull().default("pending"), // pending | completed | failed | cancelled
  metadata: jsonb("metadata"), // { plan, coins_amount, promo_code, etc. }
  invoiceUrl: text("invoice_url"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow().$onUpdate(() => new Date()),
});

export const apiKeysTable = pgTable("api_keys", {
  id: serial("id").primaryKey(),
  userId: integer("user_id").notNull().references(() => usersTable.id, { onDelete: "cascade" }),
  keyHash: text("key_hash").notNull().unique(),
  keyPrefix: text("key_prefix").notNull(), // first 8 chars for display
  name: text("name").notNull(),
  webhookUrl: text("webhook_url"),
  telegramChatId: text("telegram_chat_id"),
  whatsappNumber: text("whatsapp_number"),
  permissions: text("permissions").notNull().default("read"), // read | write | admin
  lastUsedAt: timestamp("last_used_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});
